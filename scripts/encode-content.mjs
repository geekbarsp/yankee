// Encodes content/site.json into src/generated/blob.ts so that no readable
// site text ends up in the shipped HTML/JS. A fresh random key is used on every run.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { randomBytes } from 'node:crypto';

const site = JSON.parse(readFileSync('content/site.json', 'utf8'));
site.home = JSON.parse(readFileSync('content/home.json', 'utf8'));
site.about = JSON.parse(readFileSync('content/about.json', 'utf8'));
const plain = Buffer.from(JSON.stringify(site), 'utf8');
const key = randomBytes(31);

const enc = Buffer.alloc(plain.length);
for (let i = 0; i < plain.length; i++) {
  enc[i] = plain[i] ^ key[i % key.length] ^ ((i * 131) & 255);
}

const b64 = enc.toString('base64');
const parts = [];
for (let i = 0; i < b64.length; i += 997) parts.push(b64.slice(i, i + 997));
parts.reverse();

mkdirSync('src/generated', { recursive: true });
writeFileSync(
  'src/generated/blob.ts',
  `// AUTO-GENERATED by scripts/encode-content.mjs — do not edit.\n` +
    `export const k = ${JSON.stringify(key.toString('base64'))};\n` +
    `export const d: string[] = ${JSON.stringify(parts)};\n`,
);
console.log(`[encode] ${plain.length} bytes -> src/generated/blob.ts (${parts.length} parts)`);
